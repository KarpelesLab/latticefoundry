/// A supported target architecture.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum TargetArch {
    /// 64-bit x86 (the bring-up target).
    X86_64,
    /// 64-bit ARM.
    AArch64,
    /// 64-bit RISC-V.
    Riscv64,
    /// 32-bit Arm Cortex-M, Thumb-2 (ARMv7-M / ARMv7E-M), soft-float AAPCS
    /// ([`thumb`]).
    Thumb,
    /// 32-bit WebAssembly (`wasm32`): a structured stack machine with its own
    /// module format, compiled without the register-machine pipeline (see
    /// [`wasm32`]).
    Wasm32,
    /// 8-bit AVR (AVR5 baseline: ATmega328P).
    Avr,
}

impl TargetArch {
    /// The canonical short name for this architecture.
    pub fn name(self) -> &'static str {
        match self {
            TargetArch::X86_64 => "x86_64",
            TargetArch::AArch64 => "aarch64",
            TargetArch::Riscv64 => "riscv64",
            TargetArch::Thumb => "thumbv7m",
            TargetArch::Wasm32 => "wasm32",
            TargetArch::Avr => "avr",
        }
    }
}

impl std::fmt::Display for TargetArch {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.name())
    }
}

/// A code-generation request a target cannot honor.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CodegenError {
    /// The target does not implement the requested relocation model.
    UnsupportedRelocModel {
        /// The target.
        arch: TargetArch,
        /// The requested model.
        model: RelocModel,
    },
    /// The module uses something the target cannot express (for wasm32: a
    /// `syscall`, `f16`, a second address space, a variadic call, ...).
    Unsupported {
        /// The target.
        arch: TargetArch,
        /// What is unsupported, and where.
        message: String,
    },
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CodegenError::UnsupportedRelocModel { arch, model } => write!(
                f,
                "the {arch} backend does not generate position-independent code yet \
                 (relocation model {model:?}); x86_64, aarch64 and riscv64 support PIC/PIE"
            ),
            CodegenError::Unsupported { arch, message } => write!(f, "{arch}: {message}"),
        }
    }
}

impl std::error::Error for CodegenError {}

/// Check that `arch`'s backend can honor `opts`. Position-independent code
/// ([`RelocModel::Pie`] / [`RelocModel::Pic`]) is generated by the x86-64,
/// AArch64 and RISC-V backends (GOT loads: `mov` from `sym@GOTPCREL`;
/// `adrp`+`ldr` with `R_AARCH64_ADR_GOT_PAGE`/`R_AARCH64_LD64_GOT_LO12_NC`;
/// `auipc`+`ld` with `R_RISCV_GOT_HI20`/`R_RISCV_PCREL_LO12_I`); the other
/// targets reject it.
///
/// # Errors
///
/// [`CodegenError::UnsupportedRelocModel`] for PIC on a target without it.
pub fn check_options(arch: TargetArch, opts: &CodegenOptions) -> Result<(), CodegenError> {
    let model = opts.reloc_model;
    if model.is_pic() && !matches!(arch, TargetArch::X86_64 | TargetArch::AArch64 | TargetArch::Riscv64) {
        return Err(CodegenError::UnsupportedRelocModel { arch, model });
    }
    Ok(())
}

/// Compile `module` for `arch` under `opts`: the target-generic, fallible entry
/// point over each backend's `compile_module_with`. For
/// [`TargetArch::Wasm32`] the object is an envelope around a relocatable wasm
/// object (see [`wasm32::compile_module_with`]). With
/// [`RelocModel::Pic`] (e.g. `CodegenOptions::default().with_pic(true)`) the
/// result is a position-independent relocatable object ready for a shared
/// library (link it with [`crate::link::gnu::shared_library_args`]).
///
/// # Errors
///
/// When `arch`'s backend cannot honor `opts` (see [`check_options`]), or
/// cannot compile the module ([`CodegenError::Unsupported`], wasm32 only).
pub fn compile_module_for(
    arch: TargetArch,
    module: &Module,
    syms: &StrInterner,
    opts: &CodegenOptions,
) -> Result<CompiledModule, CodegenError> {
    check_options(arch, opts)?;
    Ok(match arch {
        TargetArch::X86_64 => x86_64::compile_module_with(module, syms, opts),
        TargetArch::AArch64 => aarch64::compile_module_with(module, syms, opts),
        TargetArch::Riscv64 => riscv::compile_module_with(module, syms, opts),
        TargetArch::Thumb => thumb::compile_module_with(module, syms, opts),
        TargetArch::Wasm32 => wasm32::compile_module_with(module, syms, opts)
            .map_err(|e| CodegenError::Unsupported { arch, message: e.to_string() })?,
        TargetArch::Avr => avr::compile_module_with(module, syms, opts),
    })
}
